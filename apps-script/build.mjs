import {readFile, writeFile} from 'node:fs/promises';
const base = new URL('./',import.meta.url);
const [server,html,config] = await Promise.all([
  readFile(new URL('Server.gs',base),'utf8'),
  readFile(new URL('Index.html',base),'utf8'),
  readFile(new URL('../storefront/server/agent.json',base),'utf8')
]);
await writeFile(new URL('Code.gs',base),server + '\n// Generated by node apps-script/build.mjs. Paste this entire file into Apps Script.\n' +
  'var AGENT_CONFIG_ = ' + JSON.stringify(JSON.parse(config)) + ';\n' +
  'var CHAT_HTML_ = ' + JSON.stringify(html) + ';\n');
console.log('apps-script/Code.gs listo; no contiene claves.');
